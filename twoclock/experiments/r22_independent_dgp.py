"""R22 -- independent-DGP controls for the NYISO audit (addresses the inverse-crime caveat).

The planted controls in R12 are generated by the same LP used for inference.  Here the
synthetic unit-hours come from a DIFFERENT mechanism that no estimator in the race contains:
  D0 (null, no wear price): a smooth supply curve  p = pmin + (rmax-pmin) * logistic((m - m0)/s)
     on a noisy margin m = LBMP - c + N(0, 5), smoothed over 3 h (min-run / ramp-like inertia),
     plus 3%-of-rmax noise, with random (m0, s) per window.
  D1 (partial cap): D0 with response above sigma_true * rmax scaled by 0.5, sigma_true in {0.80, 0.90}.
Inference is the R12 estimator (sharp kink at sigma = 0.85, nameplate costs).  We report how often
the estimator excludes zero / identifies two-sided (a false-positive rate for D0) and the 3-model
race winners, for comparison with the real-data rates (79.3% excl0, 29.2% two-sided).

Run (needs the cached R12 data):  python -m twoclock.experiments.r22_independent_dgp [DATA_DIR]
"""
from __future__ import annotations
import json, os, sys
from concurrent.futures import ProcessPoolExecutor
import numpy as np

N_PER_UNIT = 10


def smooth3(x):
    k = np.ones(3) / 3.0
    return np.convolve(np.pad(x, 1, mode="edge"), k, mode="valid")


def one_unit(args):
    meta, arr, seed = args
    from twoclock.experiments import r12_unit_real_data as M
    rng = np.random.default_rng(seed)
    slices = M._window_slices(arr["ts_sec"], 168, min_frac=0.80)
    slices = [s for s in slices if int(arr["month"][s[len(s) // 2]]) not in (1, 2, 12)]
    if not slices:
        return []
    pick = rng.choice(len(slices), size=min(N_PER_UNIT, len(slices)), replace=False)
    out = []
    for k in pick:
        idx = slices[int(k)]
        lbmp = arr["lbmp_node"][idx]
        cost = arr["c_gas"][idx]
        rmax = arr["r_seas"][idx]
        pmin = np.full(len(idx), arr["pmin_val"], float)
        consec = (np.diff(arr["ts_sec"][idx]) == 3600)
        margin = lbmp - cost
        if margin.max() < 15:
            continue
        P = M.solve_kink_lp(margin, pmin, rmax, arr["ramp"], consec, sigma=0.85, w_grid=M.W_GRID)
        Pq = M.solve_quad_qp(margin, pmin, rmax, arr["ramp"], consec, g_grid=M.G_GRID)
        Pc = M.solve_cap_lp(margin, pmin, rmax, arr["ramp"], consec, th_grid=M.TH_GRID)
        m0, s = rng.uniform(5, 40), rng.uniform(5, 20)
        mt = margin + rng.normal(0, 5.0, len(idx))
        base = pmin + (rmax - pmin) / (1 + np.exp(-(mt - m0) / s))
        base = smooth3(base) + rng.normal(0, 0.03 * rmax.mean(), len(idx))
        base = np.clip(base, pmin, rmax)
        rec = {"unit": meta["unit_key"], "tech": meta["tech"], "dgp": {}}
        for name, p_obs in [("D0_null", base)] + [
                (f"D1_sigma{sg:.2f}", np.clip(np.where(base > sg * rmax, sg * rmax + 0.5 * (base - sg * rmax), base), pmin, rmax))
                for sg in (0.80, 0.90)]:
            est = M.estimate_profile(P, p_obs, M.W_GRID, M.TOL)
            sk = float(np.min(np.sum((P - p_obs[None, :]) ** 2, axis=1)))
            sq = float(np.min(np.sum((Pq - p_obs[None, :]) ** 2, axis=1)))
            sc = float(np.min(np.sum((Pc - p_obs[None, :]) ** 2, axis=1)))
            rec["dgp"][name] = {"excl0": est["excl0"], "two_sided": est["two_sided"],
                                "w_hat": est["w_hat"], "winner": ["kink", "quad", "cap"][int(np.argmin([sk, sq, sc]))]}
        out.append(rec)
    return out


def main():
    from twoclock.experiments import r12_unit_real_data as M
    from twoclock.paths import RESULTS_DIR
    if len(sys.argv) > 1:
        M.DATA_DIR = sys.argv[1]
    primary, _, _, _ = M.build_unit_dataset()
    tasks = [(u["meta"], u["arrays"], 9000 + i) for i, u in enumerate(primary)]
    with ProcessPoolExecutor(max_workers=4) as ex:
        recs = [r for part in ex.map(one_unit, tasks) for r in part]
    summ = {}
    for name in ("D0_null", "D1_sigma0.80", "D1_sigma0.90"):
        v = [r["dgp"][name] for r in recs]
        summ[name] = {"n": len(v), "excl0": float(np.mean([x["excl0"] for x in v])),
                      "two_sided": float(np.mean([x["two_sided"] for x in v])),
                      "winner_kink": float(np.mean([x["winner"] == "kink" for x in v])),
                      "winner_quad": float(np.mean([x["winner"] == "quad" for x in v])),
                      "winner_cap": float(np.mean([x["winner"] == "cap" for x in v]))}
    json.dump({"summary": summ, "records": recs}, open(os.path.join(RESULTS_DIR, "r22_independent_dgp.json"), "w"), indent=1)
    print(json.dumps(summ, indent=1))


if __name__ == "__main__":
    main()
